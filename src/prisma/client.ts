// FILE: src/prisma/client.ts  — Singleton Prisma database client
//
// CONCEPT: Prisma ORM (Object-Relational Mapper)
//   Prisma is a type-safe database client for Node.js.
//   Instead of writing raw SQL you call methods like:
//     prisma.user.findUnique({ where: { email } })
//   Prisma generates TypeScript types from your schema so every query is
//   auto-completed and type-checked.
//
// WHY A SINGLETON?
//   PrismaClient opens a connection pool (multiple DB connections held open).
//   Creating a new PrismaClient in every file would open many pools and exhaust
//   database connections. By exporting one shared instance, the entire app
//   shares a single pool.
//
// EXAMPLE USAGE:
//   import prisma from '../prisma/client';
//   const user = await prisma.user.findUnique({ where: { id: '123' } });
//   console.log(user?.email);  // 'alex@example.com'
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

// PrismaClient is the main class generated by `prisma generate`.
// It reads DATABASE_URL from process.env automatically.
import { PrismaClient } from '@prisma/client';

// Create ONE instance for the whole application (singleton pattern).
// PrismaClient under the hood manages a connection pool — not one connection per query.
const prisma = new PrismaClient();

// Default export so callers can name it however they like:
//   import prisma from '../prisma/client';
//   import db from '../prisma/client';   // also valid
export default prisma;
